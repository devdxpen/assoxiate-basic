function toVec(lon: number, lat: number): [number, number, number] {
  const p = (lat * Math.PI) / 180;
  const l = (lon * Math.PI) / 180;
  return [Math.cos(p) * Math.cos(l), Math.sin(p), Math.cos(p) * Math.sin(l)];
}

const landVecs = (() => {
  const vecs: [number, number, number][] = [];
  for (let i = 0; i < LAND.length; i += 2) {
    vecs.push(toVec(LAND[i], LAND[i + 1]));
  }
  return vecs;
})();

const cityVecs = CITIES.map((c) => toVec(c[0], c[1]));

interface ArcState {
  a: [number, number, number];
  b: [number, number, number];
  born: number;
}

const GROW = 1.7;
const HOLD = 1.3;
const FADE = 0.9;

function newPair(): [[number, number, number], [number, number, number]] {
  const i = Math.floor(Math.random() * CITIES.length);
  let j = Math.floor(Math.random() * CITIES.length);
  if (j === i)
    j =
      (j + 1 + Math.floor(Math.random() * (CITIES.length - 1))) %
      CITIES.length;
  return [cityVecs[i], cityVecs[j]];
}

function project(
  v: [number, number, number],
  rot: number,
  cx: number,
  cy: number,
  r: number
): [number, number, number] {
  const c = Math.cos(rot),
    s = Math.sin(rot);
  const x = v[0] * c + v[2] * s;
  const z = -v[0] * s + v[2] * c;
  const y = v[1];
  const y2 = y * Math.cos(TILT) - z * Math.sin(TILT);
  const z2 = y * Math.sin(TILT) + z * Math.cos(TILT);
  return [cx + x * r, cy - y2 * r, z2];
}

function slerp(
  a: [number, number, number],
  b: [number, number, number],
  t: number
): [number, number, number] {
  let d = a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
  d = Math.min(Math.max(d, -1), 1);
  const th = Math.acos(d);
  if (th < 1e-4) return [...a];
  const s = Math.sin(th),
    k1 = Math.sin((1 - t) * th) / s,
    k2 = Math.sin(t * th) / s;
  return [a[0] * k1 + b[0] * k2, a[1] * k1 + b[1] * k2, a[2] * k1 + b[2] * k2];
}

export function NetworkGlobe() {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const animIdRef = useRef<number>(0);
  const dimensionsRef = useRef({ W: 0, H: 0, CX: 0, CY: 0, R: 0 });
  const arcsRef = useRef<ArcState[]>([]);

  const resize = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    const rect = canvas.getBoundingClientRect();
    const W = rect.width;
    const H = rect.height;
    canvas.width = W * dpr;
    canvas.height = H * dpr;
    const ctx = canvas.getContext("2d");
    if (ctx) ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    dimensionsRef.current = {
      W,
      H,
      CX: W / 2,
      CY: H / 2,
      R: Math.min(W, H) * 0.4,
    };
  }, []);

  useEffect(() => {
    const initialArcs: ArcState[] = [];
    for (let k = 0; k < 4; k++) {
      const [a, b] = newPair();
      initialArcs.push({ a, b, born: 1.4 + k * 1.15 });
    }
    arcsRef.current = initialArcs;

    resize();
    window.addEventListener("resize", resize);

    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;

    function drawArc(
      arcCtx: CanvasRenderingContext2D,
      arc: ArcState,
      t: number,
      rot: number
    ) {
      const { CX, CY, R } = dimensionsRef.current;
      const age = t - arc.born;
      if (age < 0) return;
      const total = GROW + HOLD + FADE;
      if (age > total) {
        const [a, b] = newPair();
        arc.a = a;
        arc.b = b;
        arc.born = t + Math.random() * 0.8;
        return;
      }
      let head = 1,
        alpha = 1;
      if (age < GROW) head = (age / GROW) * (2 - age / GROW);
      else if (age > GROW + HOLD) alpha = 1 - (age - GROW - HOLD) / FADE;

      const N = 56;
      let prev: [number, number, number] | null = null;
      let headPt: [number, number, number] | null = null;
      arcCtx.lineWidth = 1.5;
      for (let i = 0; i <= Math.floor(N * head); i++) {
        const u = i / N;
        const p = slerp(arc.a, arc.b, u);
        const lift = 1 + 0.3 * Math.sin(Math.PI * u);
        const q = project(
          [p[0] * lift, p[1] * lift, p[2] * lift],
          rot,
          CX,
          CY,
          R
        );
        if (prev && q[2] > 0.02 && prev[2] > 0.02) {
          const segA = alpha * (0.25 + 0.65 * q[2]);
          arcCtx.strokeStyle = `rgba(${u < 0.5 ? BLUE : INDIGO},${segA.toFixed(3)})`;
          arcCtx.beginPath();
          arcCtx.moveTo(prev[0], prev[1]);
          arcCtx.lineTo(q[0], q[1]);
          arcCtx.stroke();
        }
        prev = q;
        headPt = q;
      }
      if (headPt && headPt[2] > 0.02 && age < GROW + HOLD) {
        arcCtx.beginPath();
        arcCtx.arc(headPt[0], headPt[1], 2.6, 0, 7);
        arcCtx.fillStyle = `rgba(${INDIGO},${alpha})`;
        arcCtx.shadowColor = `rgba(${INDIGO},.9)`;
        arcCtx.shadowBlur = 10;
        arcCtx.fill();
        arcCtx.shadowBlur = 0;
      }
    }

    function frame(now: number) {
      const t = now / 1000;
      const rot = (t * 2 * Math.PI) / 44;
      const { W, H, CX, CY, R } = dimensionsRef.current;

      ctx!.clearRect(0, 0, W, H);

      // Rim
      ctx!.beginPath();
      ctx!.arc(CX, CY, R, 0, 7);
      ctx!.strokeStyle = `rgba(${BLUE},.22)`;
      ctx!.lineWidth = 1;
      ctx!.stroke();

      // Land dots
      for (const v of landVecs) {
        const q = project(v, rot, CX, CY, R);
        if (q[2] <= 0) continue;
        ctx!.beginPath();
        ctx!.arc(q[0], q[1], 1.0 + 0.75 * q[2], 0, 7);
        ctx!.fillStyle = `rgba(${BLUE},${(0.1 + 0.55 * q[2]).toFixed(3)})`;
        ctx!.fill();
      }

      // City hubs
      const pulse = 0.5 + 0.5 * Math.sin(t * 2.4);
      for (const v of cityVecs) {
        const q = project(v, rot, CX, CY, R);
        if (q[2] <= 0.02) continue;
        ctx!.beginPath();
        ctx!.arc(q[0], q[1], 2.0 + 0.9 * q[2], 0, 7);
        ctx!.fillStyle = `rgba(${INDIGO},${(0.45 + 0.55 * q[2]).toFixed(3)})`;
        ctx!.shadowColor = `rgba(${INDIGO},.85)`;
        ctx!.shadowBlur = 6 + 6 * pulse;
        ctx!.fill();
        ctx!.shadowBlur = 0;
      }

      // Arcs
      for (const arc of arcsRef.current) {
        drawArc(ctx!, arc, t, rot);
      }

      animIdRef.current = requestAnimationFrame(frame);
    }

    animIdRef.current = requestAnimationFrame(frame);

    return () => {
      cancelAnimationFrame(animIdRef.current);
      window.removeEventListener("resize", resize);
    };
  }, [resize]);

  return (
    <canvas
      ref={canvasRef}
      className="absolute inset-0 w-full h-full"
      aria-hidden="true"
    />
  );
}
